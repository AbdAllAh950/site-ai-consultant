NOW = datetime(2026, 10, 5, 12, 0, tzinfo=timezone.utc)   # 15:00 in Moscow


def item(pid: str, title: str, category: str, minutes_ago: int, desc: str = "Описание") -> str:
    when = (NOW - timedelta(minutes=minutes_ago)).strftime("%a, %d %b %Y %H:%M:%S GMT")
    return f"""<item>
      <title><![CDATA[{title}]]></title>
      <link>https://www.fl.ru/projects/{pid}/slug.html</link>
      <description><![CDATA[{desc}]]></description>
      <guid>https://www.fl.ru/projects/{pid}/slug.html</guid>
      <category><![CDATA[{category}]]></category>
      <pubDate>{when}</pubDate>
    </item>"""


def feed(*items: str) -> str:   # the shape FL.ru serves, comment and CDATA included
    return ('<?xml version="1.0" encoding="utf-8"?><!--  RSS generated by FL.ru RSS Generator -->\n'
            '<rss version="2.0"><channel><title>Заказы на FL.ru</title>' + "".join(items) + "</channel></rss>")


