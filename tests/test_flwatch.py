def test_model_output_quirks():
    v = flwatch.parse_verdict('Вот ответ: {"fit": "7", "why": "x", "price": "от 25 000 ₽", "days": "5–7 дней", '
                              '"reply": "Здравствуйте!\nСтрока два"}')
    assert (v.fit, v.price, v.days) == (7, "25000", "5") and v.reply == "Здравствуйте!\nСтрока два"
    with pytest.raises(ValueError):
        flwatch.parse_verdict('{"fit": 9, "reply": ""}')


