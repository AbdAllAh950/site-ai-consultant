def test_warns_once_when_fl_is_down_and_says_when_it_is_back(tmp_path):
    async def body():
        fake = Fake()
        fake.feed = feed(OLD)
        w = watcher(tmp_path, fake)
        await w.tick(NOW)
        fake.fl_down = True
        for _ in range(7):
            await w.tick(NOW)
        warnings = [m for m in fake.sent if m["text"].startswith("⚠️")]
        assert len(warnings) == 1 and flwatch.STATUS["failures"] == 7
        fake.fl_down = False
        await w.tick(NOW)
        assert fake.sent[-1]["text"].startswith("✅ FL.ru رجع") and flwatch.STATUS["failures"] == 0
    asyncio.run(body())


