# ---------- the whole flow ----------
def settings(tmp_path, **kw) -> Settings:
    return Settings(llm_url="https://llm.test/v1/chat/completions", llm_auth="Api-Key k", llm_model="m",
                    telegram_token="123:ABC", telegram_api="https://tg.test", db_path=tmp_path / "db.sqlite",
                    fl_watch=True, fl_categories="5,31", **kw)


class Fake:
    """FL.ru (feeds + project pages), the model and Telegram in one MockTransport."""

    def __init__(self, fit=8, fl_down=False, tg_down=False):
        self.feed = feed(BOT)
        self.fit, self.fl_down, self.tg_down = fit, fl_down, tg_down
        self.llm_calls, self.sent = [], []

    def handler(self, request: httpx.Request) -> httpx.Response:
        host = request.url.host
        if host == "www.fl.ru":
            if self.fl_down:
                return httpx.Response(503)
            if request.url.path == "/rss/all.xml":
                return httpx.Response(200, content=self.feed.encode())
            return httpx.Response(200, text=PAGE)
        if host == "llm.test":
            self.llm_calls.append(json.loads(request.content))
            answer = {"fit": self.fit, "why": "مطابق لخبرتك في البوتات", "price": "9 000 ₽", "days": "5 дней",
                      "reply": "Здравствуйте! Возьмусь за **все** три задачи."}
            return httpx.Response(200, json={"choices": [{"message": {"content": "```json\n" + json.dumps(
                answer, ensure_ascii=False) + "\n```"}}]})
        if host == "tg.test":
            self.sent.append(json.loads(request.content))
            if self.tg_down == "refused":   # the relay answers 200 with Telegram's refusal inside
                return httpx.Response(200, json={"ok": False, "description": "Bad Request: can't parse entities"})
            return httpx.Response(502 if self.tg_down else 200, json={"ok": not self.tg_down})
        raise AssertionError(f"unexpected request {request.url}")

    def client(self):
        return httpx.AsyncClient(transport=httpx.MockTransport(self.handler))


def watcher(tmp_path, fake: Fake, **kw) -> FlWatch:
    s = settings(tmp_path, **kw)
    client = fake.client()
    return FlWatch(s, Notifier(s.telegram_token, s.telegram_api, client), "-100500",
                   llm=Consultant(s, client), client=client, db=tmp_path / "fl.sqlite")


def test_first_start_marks_feed_as_old_then_alerts_new_fitting_project(tmp_path):
    async def body():
        fake = Fake()
        fake.feed = feed(OLD)
        w = watcher(tmp_path, fake)
        assert await w.tick(NOW) == []
        assert len(fake.sent) == 1 and "اشتغل" in fake.sent[0]["text"] and not fake.llm_calls

        w.seen.meta("sample", "skip")              # the one-off example alert has its own test
        fake.feed = feed(OLD, BOT, VIDEO, CHEAP)
        sent = await w.tick(NOW)
        assert [p.id for p in sent] == ["5524460"]          # video: not his work; 500 ₽: too cheap
        assert len(fake.llm_calls) == 1
        task = fake.llm_calls[0]["messages"][1]["content"]
        assert "Бот присылает дубликаты" in task            # the full description from the project page
        msg = fake.sent[-1]
        assert msg["text"].startswith("🟢 <b>FL.ru · 8/10</b>") and "<pre>Здравствуйте! Возьмусь за все три задачи.</pre>" in msg["text"]
        assert "السعر <b>9000</b>" in msg["text"] and "المدة <b>5</b>" in msg["text"]
        assert msg["reply_markup"]["inline_keyboard"][0][0]["url"] == "https://www.fl.ru/projects/5524460/slug.html"
        assert "disable_notification" not in msg            # 15:00 in Moscow: with sound

        assert await w.tick(NOW) == [] and len(fake.llm_calls) == 1   # never twice
    asyncio.run(body())


